# ---------------------------------------------------------------- webhooks

def _summary_text(result: ScanResult, limit: int = 8, markdown: bool = True) -> str:
    c = result.counts()
    name = os.path.basename(result.root.rstrip("/")) or result.root
    b = "*" if markdown else ""
    head = (f"{b}vulnfind{b}: {b}{name}{b} - grade {b}{result.grade}{b} ({result.score}/100) · "
            f"{c['CRITICAL']} critical, {c['HIGH']} high, {c['MEDIUM']} medium, {c['LOW']} low")
    lines = [head]
    for f in result.findings[:limit]:
        what = f"{f.rule_id} {f.snippet}" if f.category == "dependency" else f.title
        flag = " (exploited in the wild)" if f.extra.get("kev") else ""
        lines.append(f"• [{f.severity.label}] {what}{flag} - {f.location}")
    if len(result.findings) > limit:
        lines.append(f"… and {len(result.findings) - limit} more")
    return "\n".join(lines)


def notify(url: str, result: ScanResult, timeout: float = 15) -> Tuple[bool, str]:
    host = url.split("/")[2] if "://" in url else url
    if "hooks.slack.com" in host:
        payload: Dict[str, Any] = {"text": _summary_text(result)}
    elif "discord" in host:
        payload = {"content": _summary_text(result, markdown=True).replace("*", "**")[:1900]}
    elif "office.com" in host or "logic.azure.com" in host:
        payload = {"text": _summary_text(result).replace("\n", "<br>")}
    else:
        payload = {
            "tool": "vulnfind", "version": __version__, "root": result.root, "grade": result.grade, "score": result.score,
            "counts": result.counts(), "total": len(result.findings), "text": _summary_text(result, markdown=False),
            "findings": [f.to_dict() for f in result.findings[:50]],
        }
    req = urllib.request.Request(url, data=json.dumps(payload).encode(), method="POST",
                                 headers={"Content-Type": "application/json", "User-Agent": f"vulnfind/{__version__}"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return True, f"HTTP {resp.status}"
    except Exception as e:
        return False, f"{e.__class__.__name__}: {e}"


# ---------------------------------------------------------------- compare two JSON reports

def load_report(path: str) -> Dict[str, Any]:
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)
    if isinstance(data, list):  # multi-path report: merge
        merged = {"findings": []}
        for r in data:
            merged["findings"] += r.get("findings", [])
        return merged
    return data


def compare(old: Dict[str, Any], new: Dict[str, Any]) -> Dict[str, List[dict]]:
    old_f = {f["fingerprint"]: f for f in old.get("findings", [])}
    new_f = {f["fingerprint"]: f for f in new.get("findings", [])}
    order = lambda f: (-Severity.parse(f["severity"]), f["file"], f.get("line") or 0)
    return {
        "new": sorted((f for k, f in new_f.items() if k not in old_f), key=order),
        "fixed": sorted((f for k, f in old_f.items() if k not in new_f), key=order),
        "unchanged": sorted((f for k, f in new_f.items() if k in old_f), key=order),
    }


# ---------------------------------------------------------------- watch mode

def snapshot(root: str, files) -> Dict[str, Tuple[float, int]]:
    out = {}
    for f in files:
        try:
            st = os.stat(f.path)
        except OSError:
            continue
        out[f.rel] = (st.st_mtime, st.st_size)
    return out


def watch(root: str, list_files: Callable[[], list], on_change: Callable[[set], None], interval: float = 1.5) -> None:
    prev = snapshot(root, list_files())
    while True:
        time.sleep(interval)
        cur = snapshot(root, list_files())
        changed = {k for k in cur if prev.get(k) != cur[k]} | {k for k in prev if k not in cur}
        if changed:
            on_change(changed)
            prev = cur
