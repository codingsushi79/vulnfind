def find_config(root: str, explicit: Optional[str] = None) -> Optional[str]:
    if explicit:
        return explicit
    for name in CONFIG_NAMES:
        p = os.path.join(root, name)
        if os.path.isfile(p):
            return p
    return None


def load_config(path: str) -> Dict[str, Any]:
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)
    if not isinstance(data, dict):
        raise ValueError(f"{path}: expected a JSON object")
    out: Dict[str, Any] = {}
    for key, value in data.items():
        k = key.replace("-", "_")
        if k.startswith("$") or k == "comment":
            continue
        if k not in CONFIG_KEYS:
            raise ValueError(f"{path}: unknown option {key!r} (valid: {', '.join(sorted(CONFIG_KEYS))})")
        want = CONFIG_KEYS[k]
        if want is list and isinstance(value, str):
            value = [value]
        if want is str and isinstance(value, list):
            value = ",".join(value)
        if not isinstance(value, want):
            raise ValueError(f"{path}: option {key!r} should be {want.__name__}")
        out[k] = value
    return out


